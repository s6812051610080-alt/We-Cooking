#include <stdio.h>

int main() {
    // กำหนดค่าเริ่มต้นของตัวแปรตามโจทย์
    int a = 5, b = 2;
    float x = 3.0, y = 4.5;

    // คำนวณนิพจน์ที่ 1
    int r1 = a++ * b + (int)y % 3;

    // รีเซ็ตค่าตัวแปรกลับเป็นค่าเริ่มต้นก่อนคิดนิพจน์ถัดไป
    a = 5; b = 2; x = 3.0; y = 4.5;
    
    // คำนวณนิพจน์ที่ 2
    int r2 = (a > b) && ((int)x / b < 2);

    // รีเซ็ตค่าตัวแปร
    a = 5; b = 2; x = 3.0; y = 4.5;
    
    // คำนวณนิพจน์ที่ 3
    float r3 = ++x * y - a / 2;

    // รีเซ็ตค่าตัวแปร
    a = 5; b = 2; x = 3.0; y = 4.5;
    
    // คำนวณนิพจน์ที่ 4
    float r4 = ((x += 1.5) > y) || (b-- > 0);

    // แสดงผลลัพธ์
    printf("r1 = %d\n", r1);
    printf("r2 = %d\n", r2);
    printf("r3 = %.2f\n", r3);
    printf("r4 = %.2f\n", r4);

    return 0;
}