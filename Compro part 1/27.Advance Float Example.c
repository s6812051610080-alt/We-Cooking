#include <stdio.h> // เรียกใช้ไลบรารีมาตรฐานสำหรับแสดงผลทางหน้าจอ (printf)

int main() {
    // ประกาศตัวแปรตามข้อมูลที่จะแสดงผลในตาราง
    float a = 0.617;
    int b = 25;
    float c = 19.000;
    int d = 9;
    float e = 124.555;
    float f = 0.001;

    // บรรทัดที่ 1: "a  =  0.617%" (กำหนดความกว้างเพื่อจัดตำแหน่งให้ตรงช่อง)
    printf("%-3s=  %6.3f%%\n", "a", a);

    // บรรทัดที่ 2: "b  =   25%"
    printf("%-3s=  %5d%%\n", "b", b);

    // บรรทัดที่ 3: "c   = 19.000%"
    printf("%-4s= %6.3f%%\n", "c", c);

    // บรรทัดที่ 4: "d   = 9 %"
    printf("%-4s= %d %%\n", "d", d);

    // บรรทัดที่ 5: "e  = 124.555%"
    printf("%-3s= %7.3f%%\n", "e", e);

    // บรรทัดที่ 6: "f  = 0.001%"
    printf("%-3s= %6.3f%%\n", "f", f);

    return 0; // คืนค่า 0 เพื่อบอกว่าโปรแกรมทำงานเสร็จสมบูรณ์
}