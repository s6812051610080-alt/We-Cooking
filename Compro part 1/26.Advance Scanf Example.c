#include <stdio.h>

int main() {
    // === ประกาศตัวแปรสำหรับข้อมูลส่วนบุคคล (บรรทัดที่ 1) ===
    char name[30];    // ประกาศตัวแปรเก็บชื่อ เป็น string ขนาด 30 ตัวอักษร
    int age;          // ประกาศตัวแปรเก็บอายุ เป็นเลขจำนวนเต็ม
    float height;     // ประกาศตัวแปรเก็บส่วนสูง เป็นเลขทศนิยม

    // === ประกาศตัวแปรสำหรับข้อมูลผลการเรียน (บรรทัดที่ 2) ===
    char subject;     // ประกาศตัวแปรเก็บตัวอักษรพิมพ์ใหญ่ตัวแรกของชื่อวิชา
    float grade;      // ประกาศตัวแปรเก็บเกรดที่ได้ เป็นเลขทศนิยม
    char grade_letter;// ประกาศตัวแปรเก็บตัวอักษรแทนเกรด (1 ตัวอักษร)

    // === รับข้อมูลบรรทัดที่ 1 (ข้อมูลส่วนบุคคล) ===
    // รับข้อมูล: ชื่อ (string), อายุ (integer), ส่วนสูง (float)
    scanf("%s %d %f", name, &age, &height);

    // === รับข้อมูลบรรทัดที่ 2 (ข้อมูลผลการเรียน) ===
    // เว้นวรรคหน้า %c เพื่อข้ามช่องว่าง/ขึ้นบรรทัดใหม่จากคำสั่ง scanf ก่อนหน้า
    // รับข้อมูล: ชื่อวิชา (char), เกรด (float), ตัวอักษรเกรด (char)
    scanf(" %c %f %c", &subject, &grade, &grade_letter);

    // === แสดงผลข้อมูล 2 ประโยค (ประโยคละ 1 บรรทัด) ===
    // ประโยคที่ 1: แสดงตัวอักษรตัวแรกของชื่อ (%c ใช้ name[0]), อายุ (%d), ส่วนสูงทศนิยม 1 ตำแหน่ง (%.1f)
    printf("%c is %d years old and %.1f centimeters tall.\n", name[0], age, height);

    // ประโยคที่ 2: แสดงชื่อวิชา (%c), เกรดทศนิยม 2 ตำแหน่ง (%.2f), ตัวอักษรแทนเกรด (%c)
    printf("In subject %c, %c got %.2f which is symbolized as '%c'.\n", subject, name[0], grade, grade_letter);

    return 0; // คืนค่า 0 เพื่อบอกว่าโปรแกรมทำงานเสร็จสมบูรณ์
}