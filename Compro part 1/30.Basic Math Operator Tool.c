#include <stdio.h>

int main() {
    int a = 10, b = 3;

    printf("assign >> a = %d and b = %d\n", a, b);

    printf("a + b = %d\n", a + b);
    printf("a - b = %d\n", a - b);
    printf("a * b = %d\n", a * b);
    printf("a / b = %d\n", a / b);
    printf("a mod b = %d\n", a % b);

    return 0;
}