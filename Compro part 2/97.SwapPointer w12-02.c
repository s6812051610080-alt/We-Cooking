#include <stdio.h>

// TODO: เขียนฟังก์ชัน swap ที่รับ int *a, int *b แล้วสลับค่า
void swap(int *a, int *b) {
    int temp = *a;
    *a = *b;
    *b = temp;
}

int main() {
    int a = 5, b = 10;

    // แสดงค่าก่อนสลับ
    printf("Before swap: a = %d, b = %d\n", a, b);

    // เรียกใช้ swap
    swap(&a, &b);

    // แสดงค่าหลังสลับ
    printf("After  swap: a = %d, b = %d\n", a, b);

    return 0;
}

// === คำอธิบายการทำงานของโปรแกรม ===
// 1. สร้างฟังก์ชัน swap ที่รับพารามิเตอร์เป็น pointer (int *a, int *b) เพื่อให้สามารถแก้ไขค่าตัวแปรต้นฉบับได้ (Pass by Reference)
// 2. ในฟังก์ชัน swap ใช้ตัวแปรชั่วคราว temp เพื่อพักค่า *a นำค่า *b มาใส่ใน *a แล้วนำค่า temp ไปใส่ใน *b ทำให้ค่าในตำแหน่งหน่วยความจำถูกสลับกัน
// 3. ใน main() ประกาศตัวแปร a = 5 และ b = 10 พร้อมสั่ง printf แสดงค่าก่อนสลับ
// 4. สั่ง swap(&a, &b) โดยส่ง address (&) ของ a และ b ไปยังฟังก์ชัน swap
// 5. ค่าในตัวแปร a และ b ถูกสลับกันจริง เมื่อใช้ printf แสดงค่าหลังสลับ จึงได้ผลลัพธ์เป็น a = 10, b = 5