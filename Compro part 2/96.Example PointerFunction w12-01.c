#include <stdio.h>

int main() {
    int x = 10;
    int *ptr;

    // TODO: เขียนคำสั่งให้ ptr ชี้ไปที่ x
    ptr = &x;

    // TODO: แสดงค่าของ x ก่อนเปลี่ยน
    printf("Before: x = %d\n", x);

    // TODO: ใช้ pointer เปลี่ยนค่า x ให้เป็น 20
    *ptr = 20;

    // TODO: แสดงค่าของ x หลังเปลี่ยน
    printf("After : x = %d\n", x);

    return 0;
}

// === คำอธิบายการทำงานของโปรแกรม ===
// 1. ประกาศตัวแปร x มีค่าเป็น 10 และประกาศตัวแปร pointer ชื่อ ptr
// 2. ptr = &x; คือการเอาที่อยู่ (address) ของตัวแปร x ไปเก็บไว้ใน ptr ทำให้ ptr ชี้ไปที่ x
// 3. printf แสดงค่าของ x ก่อนแก้ไข ซึ่งคือ 10
// 4. *ptr = 20; คือการเข้าถึงค่าผ่าน pointer แล้วทำการเปลี่ยนค่าในตำแหน่งที่ ptr ชี้อยู่ (ซึ่งก็คือตัวแปร x) ให้กลายเป็น 20
// 5. printf แสดงค่าของ x หลังจากถูกเปลี่ยนค่าผ่าน pointer แล้ว ซึ่งได้ผลลัพธ์เป็น 20