#include <stdio.h>

int main() {
    int i = 2; // กำหนดค่าเริ่มต้น i = 2

    // ตรวจสอบเงื่อนไข ถ้า i ยังน้อยกว่าหรือเท่ากับ 10 ให้ทำใน loop
    while (i <= 10) {
        printf("%d ", i); // แสดงค่า i
        i += 2;          // เพิ่มค่า i ทีละ 2
    }

    printf("\nEnd of loop\n"); // แสดงข้อความเมื่อจบ loop

    return 0;
}

/* 
  คำอธิบายการทำงาน (while loop):
  1. เริ่มต้นกำหนดตัวแปร i มีค่าเท่ากับ 2
  2. โปรแกรมจะตรวจสอบเงื่อนไขใน while (i <= 10)
  3. ในรอบแรก i = 2 เงื่อนไขเป็นจริง (True) จะพิมพ์เลข 2 ออกทางหน้าจอ แล้วเพิ่มค่า i ขึ้นอีก 2 (เป็น 4)
  4. ทำการวนรอบตรวจสอบเงื่อนไขเรื่อยๆ พิมพ์ค่า 4, 6, 8, 10
  5. เมื่อจบการพิมพ์เลข 10 ค่า i จะถูกเพิ่มเป็น 12
  6. โปรแกรมกลับมาเช็กเงื่อนไข 12 <= 10 ซึ่งเป็นเท็จ (False) จึงหลุดออกจาก loop
  7. แสดงข้อความ "End of loop" บนบรรทัดใหม่ แล้วจบการทำงาน
*/