#include <stdio.h>

int main() {
    // กำหนดค่าเริ่มต้น i = 2, เช็กเงื่อนไข i <= 10, เพิ่มค่า i ทีละ 2 ในทุกๆ รอบ
    for (int i = 2; i <= 10; i += 2) {
        printf("%d ", i); // แสดงค่า i
    }

    printf("\nEnd of loop\n"); // แสดงข้อความเมื่อจบ loop

    return 0;
}

/* 
  คำอธิบายการทำงาน (for loop):
  1. กำหนดค่าเริ่มต้นให้ i = 2 ในส่วนแรกของ for loop
  2. ตรวจสอบเงื่อนไขส่วนที่สอง (i <= 10) หากเป็นจริง จะเข้ามาทำงานในบล็อก { } โดยพิมพ์ค่า i ออกมา
  3. หลังจากแสดงผลเสร็จ จะทำตามเงื่อนไขส่วนที่สาม (i += 2) คือเพิ่มค่า i ขึ้นทีละ 2
  4. วนทำซ้ำตามขั้นตอนเดิม พิมพ์ค่า 2, 4, 6, 8, 10
  5. เมื่อ i ถูกบวกเพิ่มเป็น 12 เงื่อนไข (12 <= 10) จะกลายเป็นเท็จ (False) ทำให้หยุดการทำงานของ for loop
  6. แสดงข้อความ "End of loop" บนบรรทัดใหม่ แล้วจบการทำงาน
*/